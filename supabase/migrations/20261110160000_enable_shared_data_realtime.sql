do $$
declare
  table_name text;
begin
  if not exists (
    select 1
    from pg_publication
    where pubname = 'supabase_realtime'
  ) then
    raise exception 'Publikasi supabase_realtime tidak ditemukan. Aktifkan Realtime pada proyek Supabase terlebih dahulu.';
  end if;

  foreach table_name in array array['map_points', 'umkm_records', 'economy_records']
  loop
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = table_name
    ) then
      execute format('alter publication supabase_realtime add table public.%I', table_name);
    end if;
  end loop;
end;
$$;
